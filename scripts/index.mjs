#!/usr/bin/env node
// Generates every index from frontmatter. Deterministic, so the check can
// compare each one byte for byte (S6). Nobody edits these by hand.
//
//   context/INDEX.md           stable context entries, lessons, persona observations
//   product/feature-index.yaml area > feature > work folders, prds, tickets, jira, outcome
//   product/rooftops.yaml      rooftop id map: freshdesk company id, arali company, work folders

import { writeFileSync, readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, KINDS, PERSONAS, entries, rule, parseEntry } from "./lib.mjs";

const TITLES = {
  "data-trap": "Data traps (read before any metric query)",
  "metric-definition": "Metric definitions",
  "system-fact": "System facts",
  "decision": "Decisions",
  "lesson": "Lessons (loaded by the skill or reviewer named in brackets)",
  "observation": "Persona observations (loaded by that persona at review time)",
};

export function renderIndex() {
  const live = entries("context").filter(e => e.parsed && e.parsed.meta.status === "stable");
  const out = [
    "# PM OS context index",
    "",
    "Generated by `node scripts/index.mjs`. Do not edit by hand.",
    "One line per stable entry: path, area, rule. Load an entry only when its rule is relevant.",
    "Company and dealer-domain context lives in the org `us-dealer-domain` skill, not here.",
    "Persona cores live in `context/personas/<role>/core.md`.",
    "",
  ];
  for (const kind of Object.keys(KINDS)) {
    const rows = live.filter(e => e.parsed.meta.kind === kind)
      .sort((a, b) => a.path.localeCompare(b.path));
    out.push(`## ${TITLES[kind]}`, "");
    if (!rows.length) out.push("_None yet._");
    for (const e of rows) {
      const m = e.parsed.meta;
      const tag = kind === "lesson" ? `${m.area}, ${m.target}` : kind === "observation" ? `${m.persona}, ${m.support_rooftops} rooftops, seen ${m.last_seen}` : m.area;
      out.push(`- \`${e.path}\` [${tag}] ${rule(e.parsed.body)}`);
    }
    out.push("");
  }
  return out.join("\n");
}

// ---------- product indexes ----------
function workFolders() {
  const base = join(ROOT, "product", "work");
  if (!existsSync(base)) return [];
  const out = [];
  for (const area of readdirSync(base).sort()) {
    const ap = join(base, area);
    if (!statSync(ap).isDirectory()) continue;
    for (const w of readdirSync(ap).sort()) {
      const cp = join(ap, w, "case.md");
      if (!existsSync(cp)) continue;
      const parsed = parseEntry(readFileSync(cp, "utf8"));
      if (parsed) out.push({ dir: `product/work/${area}/${w}`, meta: parsed.meta });
    }
  }
  return out;
}

const q = (v) => (/^[A-Za-z0-9_./-]+$/.test(String(v)) ? String(v) : JSON.stringify(String(v)));

function featureIndex(work) {
  const tree = {};
  for (const { dir, meta } of work) {
    const area = meta.area || "unknown";
    const feature = meta.feature || "unassigned";
    ((tree[area] ||= {})[feature] ||= []).push({ dir, meta });
  }
  const out = ["# Generated by node scripts/index.mjs. Do not edit by hand.", "# area > feature > work items, each with its ticket, stage, outcome, prd and jira.", ""];
  if (!work.length) out.push("{}");
  for (const area of Object.keys(tree).sort()) {
    out.push(`${q(area)}:`);
    for (const feature of Object.keys(tree[area]).sort()) {
      out.push(`  ${q(feature)}:`);
      for (const { dir, meta } of tree[area][feature]) {
        out.push(`    - work: ${q(dir)}`);
        for (const k of ["freshdesk_ticket", "stage", "outcome", "prd", "jira", "ledger_match"]) if (meta[k]) out.push(`      ${k}: ${q(meta[k])}`);
      }
    }
  }
  return out.join("\n") + "\n";
}

function rooftops(work) {
  const map = {};
  for (const { dir, meta } of work) {
    if (!meta.rooftop_slug) continue;
    const r = (map[meta.rooftop_slug] ||= { work: [] });
    for (const k of ["rooftop_name", "freshdesk_company_id", "arali_company", "area"]) if (meta[k] && !r[k]) r[k] = meta[k];
    r.work.push(dir);
  }
  const out = ["# Generated by node scripts/index.mjs. Do not edit by hand.", "# Id map only. Customer context is read live from Arali, never stored here.", ""];
  if (!Object.keys(map).length) out.push("{}");
  for (const slug of Object.keys(map).sort()) {
    const r = map[slug];
    out.push(`${q(slug)}:`);
    for (const k of ["rooftop_name", "freshdesk_company_id", "arali_company", "area"]) if (r[k]) out.push(`  ${k}: ${q(r[k])}`);
    out.push("  work:");
    for (const w of r.work) out.push(`    - ${q(w)}`);
  }
  return out.join("\n") + "\n";
}

export function renderProductIndexes() {
  const work = workFolders();
  return { "product/feature-index.yaml": featureIndex(work), "product/rooftops.yaml": rooftops(work) };
}

// Persona loading helper for skills: core plus top N observations for an area and tags.
export function personaContext(persona, { area, tags = [], limit = 10 } = {}) {
  if (!PERSONAS.includes(persona)) throw new Error(`unknown persona ${persona}`);
  const corePath = join(ROOT, "context", "personas", persona, "core.md");
  const core = existsSync(corePath) ? readFileSync(corePath, "utf8") : "";
  const obs = entries(`context/personas/${persona}/observations`)
    .filter(e => e.parsed?.meta.status === "stable" && e.parsed.meta.kind === "observation")
    .map(e => {
      const m = e.parsed.meta;
      const t = (m.tags || "").replace(/[[\]]/g, "").split(",").map(s => s.trim()).filter(Boolean);
      const score = (m.area === area ? 2 : 0) + t.filter(x => tags.includes(x)).length * 3 + Number(m.support_rooftops || 0) * 0.5 - (Date.now() - Date.parse(m.last_seen)) / 86_400_000 / 30;
      return { path: e.path, id: m.id, score, text: e.text };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
  return { core, observations: obs };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === "persona") {
    const [, , , persona, area, tags] = process.argv;
    const r = personaContext(persona, { area, tags: (tags || "").split(",").filter(Boolean) });
    console.log(r.core);
    console.log(`\n# Observations loaded (${r.observations.length})\n`);
    for (const o of r.observations) console.log(`<observation path="${o.path}">\n${o.text}\n</observation>\n`);
    process.exit(0);
  }
  writeFileSync(join(ROOT, "context", "INDEX.md"), renderIndex());
  for (const [rel, text] of Object.entries(renderProductIndexes())) writeFileSync(join(ROOT, rel), text);
  console.log("wrote context/INDEX.md, product/feature-index.yaml, product/rooftops.yaml");
}
